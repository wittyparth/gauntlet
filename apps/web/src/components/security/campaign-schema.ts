import { z } from "zod";

import { dollarsToMicros } from "@/lib/format";
import type { Attack } from "@/lib/api/hooks/attacks";

export const campaignSchema = z.object({
  version_id: z.string().min(1, "Choose an agent version"),
  suite_id: z.string().min(1, "Choose a benign suite"),
  categories: z.array(z.string()).min(1, "Choose at least one attack category"),
  repetitions: z.number().int("Whole number").min(1, "At least 1"),
  max_attacks: z.number().int("Whole number").min(1, "At least 1"),
  budget_dollars: z.number().positive("Budget must be above 0"),
});

export type CampaignInput = z.input<typeof campaignSchema>;

export type LibraryFilters = { categories: string[]; vector: string; source: string; q: string };

/** The source family of a library attack: `garak@abc:xyz` becomes `garak`. */
export const sourceFamily = (source: string) => source.split(/[@:]/)[0] ?? source;

export function filterAttacks(attacks: Attack[], f: LibraryFilters): Attack[] {
  const q = f.q.trim().toLowerCase();
  return attacks.filter(
    (a) =>
      f.categories.includes(a.category) &&
      (f.vector === "all" || a.vector === f.vector) &&
      (f.source === "all" || sourceFamily(a.source) === f.source) &&
      (q === "" || `${a.title} ${a.technique} ${a.id}`.toLowerCase().includes(q)),
  );
}

/** Library narrowing beyond categories: when set the campaign names its attacks explicitly. */
export const isNarrowed = (f: LibraryFilters) => f.vector !== "all" || f.source !== "all" || f.q.trim() !== "";

export const budgetMicros = (dollars: number) => dollarsToMicros(dollars);

/** The typed confirmation must equal the agent name, ignoring surrounding spaces. */
export const confirmationMatches = (typed: string, agentName: string) => typed.trim() === agentName.trim();

type SuiteLike = { id: string; scenarios: string[] };
type ScenarioLike = { id: string; scenario: { world: string | { id?: string | null } } };

/**
 * Suites a campaign can use as its benign tasks: not generated by an earlier campaign, and every
 * scenario belongs to the version's world.
 */
export function benignSuites<T extends SuiteLike>(suites: T[], scenarios: ScenarioLike[], worldId: string | null): T[] {
  const world = new Map(scenarios.map((s) => [s.id, typeof s.scenario.world === "string" ? s.scenario.world : (s.scenario.world.id ?? "")]));
  return suites.filter(
    (s) =>
      !s.id.startsWith("suite_campaign_") &&
      s.scenarios.length > 0 &&
      (worldId === null || s.scenarios.every((id) => world.get(id) === worldId)),
  );
}

/** Advanced attack ids: comma, space or newline separated; blanks and repeats dropped. */
export function parseAttackIds(raw: string): string[] {
  return [...new Set(raw.split(/[\s,]+/).filter((x) => x !== ""))];
}

/** Ids that are not in the attack library. */
export const unknownAttackIds = (ids: string[], library: Attack[]): string[] => {
  const known = new Set(library.map((a) => a.id));
  return ids.filter((id) => !known.has(id));
};
