"""`python -m tools.import_attacks.notices`: generate `attacks/NOTICES.md` from the library.

Per source: project, repository, pin, licence, the licence text copied verbatim from the
upstream checkout (`--licence-file source=PATH`), counts imported and skipped.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

import yaml

from .common import REPO_ROOT, SOURCE_PRIORITY, load_mapping


def render(out_dir: Path, licence_texts: dict[str, str]) -> str:
    skipped = json.loads((out_dir / "skipped.json").read_text())
    parts = [
        "# Third-party attack content\n",
        "Generated by `python -m tools.import_attacks.notices`; do not edit by hand. Every attack",
        "in `attacks/library/` was read from the upstream projects below (never authored here)",
        "and keeps the source and licence in its `source` and `license` fields.\n",
    ]
    for source in SOURCE_PRIORITY:
        files = sorted((out_dir / source).glob("*.yaml"))
        if not files:
            continue
        m = load_mapping(source)
        rows = [r for f in files for r in yaml.safe_load(f.read_text())]
        pins = sorted({r["source"].split("@", 1)[1].split(":", 1)[0] for r in rows})
        reasons = Counter(skipped.get(source, {}).get("counts", {}))
        breakdown = ", ".join(f"{k} {v}" for k, v in sorted(reasons.items()))
        parts += [
            f"## {m['project']}\n",
            f"* Repository: {m['repo']}",
            f"* Pinned version or commit: {', '.join(pins)}",
            f"* Licence: {m['license']}",
            f"* Imported: {len(rows)}",
            f"* Skipped: {sum(reasons.values())} ({breakdown})\n",
            "Licence notice (verbatim from the upstream repository):\n",
            "```text",
            licence_texts.get(source, "(not provided)").strip(),
            "```\n",
        ]
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="tools.import_attacks.notices")
    ap.add_argument("--out", type=Path, default=REPO_ROOT / "attacks" / "library")
    ap.add_argument("--licence-file", action="append", default=[], metavar="SOURCE=PATH")
    a = ap.parse_args(argv)
    texts = {}
    for item in a.licence_file:
        source, _, path = item.partition("=")
        texts[source] = Path(path).read_text()
    (a.out.parent / "NOTICES.md").write_text(render(a.out, texts))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
