"""Shared bits of the reference generators: output dir, write-or-check."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "user" / "reference"
BANNER = "<!-- Generated by {gen}. Do not edit; run `uv run python -m tools.docs.{mod}`. -->\n\n"


def write_or_check(files: dict[str, str], argv: list[str]) -> int:
    """Write `files` under docs/user/reference/, or with --check fail if any differs."""
    stale = [n for n, t in files.items() if not (OUT / n).is_file() or (OUT / n).read_text() != t]
    if "--check" in argv:
        for n in stale:
            print(f"stale: docs/user/reference/{n}", file=sys.stderr)
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for n in stale:
        (OUT / n).write_text(files[n])
        print(f"wrote docs/user/reference/{n}")
    return 0
