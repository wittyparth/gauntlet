from datetime import UTC, datetime

from studies.common import StudyResult
from studies.render import render

R = StudyResult(
    name="demo", seed=7, platform_version="0.1.0", started_at=datetime(2026, 1, 2, tzinfo=UTC),
    metrics={"b": 0.25, "a": 0.5}, intervals={"a": (0.4, 0.6)}, n=12,
    limitations=["small sample"], notes="note",
)  # fmt: skip

GOLDEN = """# Benchmarks

Generated by `uv run python -m studies.render` from `benchmarks/results/*.json`. Negative results are kept; intervals are 95 percent; nothing is rounded up.

## demo

Platform 0.1.0, seed 7, n = 12, run 2026-01-02T00:00:00+00:00

| Metric | Value | 95% interval |
|---|---|---|
| a | 0.5 | 0.4 to 0.6 |
| b | 0.25 | n/a |

Limitations:

- small sample

Notes: note
"""  # noqa: E501


def test_golden_page():
    assert render([R]) == GOLDEN


def test_deterministic_and_sorted():
    other = R.model_copy(update={"name": "alpha"})
    assert render([R, other]) == render([other, R])
    assert render([R, other]).index("## alpha") < render([R, other]).index("## demo")


def test_empty_page():
    assert "No study results" in render([])
